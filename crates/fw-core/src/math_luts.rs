//! Committed Q32 LUT tables for `fw-core::math`.
//!
//! T1-10 (Codex 2026-05-16 audit P1 closure): the prior `math.rs` built
//! `SIGMOID_LUT` + `EXP_LUT` at process startup via `LazyLock` using
//! `f64::exp()` then quantized to Q32. Cross-OS hash passed today but the
//! bake step was libm/platform-dependent by design — a future
//! libc/glibc/macOS-libsystem change in `exp()`'s ULP behavior at one of
//! the 257 LUT points could silently drift the bake and break determinism
//! without any code change. T1-10 commits the baked output as source byte
//! sequence so drift becomes a code-review artifact, not a silent runtime
//! issue.
//!
//! # Bake source
//!
//! - `LUT_N = 257` entries per table (defined in math.rs)
//! - Domain `[-8, +8]` with stride `1/16` (per `LUT_MIN` / `LUT_MAX` /
//!   `STEP_F64` in the original `math.rs` LazyLock closures)
//! - SIGMOID: entry `i` = `Q32::from_f64_clamped(1.0 / (1.0 + (-x).exp()))`
//!   where `x = -8.0 + (i as f64) * (16.0 / 256.0)`
//! - EXP: entry `i` = `Q32::from_f64_clamped(x.exp())` over the same x range
//!
//! # Regeneration procedure
//!
//! 1. Run the drift-detection test to confirm the committed values still
//!    match the f64 reference on the current toolchain:
//!    ```text
//!    cargo test --package fw-core --test lut_drift_detection -- --ignored
//!    ```
//!    If it passes, no regeneration needed.
//!
//! 2. If the drift test fails (or the LUT structure changes — `LUT_N`,
//!    domain bounds, or formula), regenerate via the printer test (kept
//!    `#[ignore]`-gated; never runs by default):
//!    ```text
//!    cargo test --package fw-core --test print_luts_oneshot -- --ignored --nocapture --test-threads=1
//!    ```
//!    Pipe stdout, extract the two `pub(crate) const ... = [ ... ];`
//!    blocks, paste-replace below. Re-run the drift test to confirm.
//!
//! 3. **Canonical-hash impact** — regenerating these values WILL rebaseline
//!    the pinned BLAKE3 hash in `crates/fw-replay/tests/canonical_hash.rs`
//!    (the math LUTs feed every utility-scored decision in the BT). An
//!    authorized regeneration must update the pinned hash + cite the
//!    rebaseline reason per ADR-0012.
//!
//! # Wire shape
//!
//! Raw `i64` (not `Q32`) so this file is pure data with no fw-core import
//! cycles. `math.rs`'s const-fn helper maps `[i64; N] -> [Q32; N]` via
//! `Q32::from_raw` at compile time.

