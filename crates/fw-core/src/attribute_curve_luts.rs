//! Committed Q32 LUT tables for `fw-core::attribute_curve`.
//!
//! Five per-class gamma power-curve LUTs `g(a) = a^γ` over the domain `[0, 1]`,
//! 257 entries each (256 uniform segments, step `1/256`). The curve makes
//! elite attribute values disproportionately impactful (Slice 0 of the
//! attribute-effect mandate); see `attribute_curve.rs` + the design doc
//! `docs/design/attribute-effect-audit-2026-06-06.md` §3.
//!
//! # Bake source
//!
//! - 257 entries per table; entry `i` corresponds to `a = i / 256`.
//! - Each entry = `Q32::from_f64_clamped(a.powf(γ))` (round-to-nearest-even).
//! - γ per class (§3.3): SKILL 1.7, PHYSICAL 1.4, CONTEST 1.8, MENTAL 1.6,
//!   PERSONALITY 1.3.
//!
//! # Regeneration procedure
//!
//! 1. Confirm drift against the f64 reference on the current toolchain:
//!    ```text
//!    cargo test --package fw-core --test attribute_curve_drift_detection -- --ignored
//!    ```
//!    If it passes, no regeneration needed.
//!
//! 2. If it fails (or the LUT structure / γ changes), regenerate via the
//!    printer test:
//!    ```text
//!    cargo test --package fw-core --test print_attribute_curve_luts -- --ignored --nocapture --test-threads=1
//!    ```
//!    Pipe stdout, extract the five `pub(crate) const ..._LUT_RAW = [ ... ];`
//!    blocks, paste-replace below. Re-run the drift test to confirm.
//!
//! 3. **Canonical-hash impact** — regenerating WILL rebaseline the pinned
//!    BLAKE3 hash in `crates/fw-replay/tests/canonical_hash.rs` (the curve
//!    feeds every utility-scored decision + physics coefficient). An
//!    authorized regeneration updates the pinned hash + cites the reason.
//!
//! # Wire shape
//!
//! Raw `i64` (not `Q32`) so this file is pure data; `attribute_curve.rs`'s
//! const-fn helper maps `[i64; N] -> [Q32; N]` via `Q32::from_raw` at compile
//! time.

